local T = require("framework")
local H = require("helpers")
local Mock = require("pawhome.adapters.mock")
local App = require("pawhome.app")
local Storage = require("pawhome.core.storage")
local Serialize = require("pawhome.core.serialize")

local function petNames(app)
    local out = {}
    for _, p in ipairs(app:view(1, 101).pets) do out[#out + 1] = p.name end
    return table.concat(out, ",")
end

local function adoptNamed(app, name)
    local o = app:offers(1, true)
    local r = app:adoptOffer(1, 101, o[1].id, name)
    assert(r.ok, r.message)
end

T.test("slots: switching saves shows each save's own pets and never mixes them", function()
    local app, mock = H.new({ slotted = true, money = 5000 })
    adoptNamed(app, "Alpha")
    mock.switchSlot("slot2")
    T.eq(petNames(app), "", "the new save has no pets")
    adoptNamed(app, "Beta")
    T.eq(petNames(app), "Beta")
    mock.switchSlot("slot1")
    T.eq(petNames(app), "Alpha")
    mock.switchSlot("slot2")
    T.eq(petNames(app), "Beta")
end)

T.test("slots: a tick after switching never writes the old save's data into the new slot", function()
    local app, mock = H.new({ slotted = true, money = 5000 })
    adoptNamed(app, "Alpha")
    mock.slot = "slot2"            -- the adapter now points at slot2; nobody told the mod yet
    mock.clock = mock.clock + 60
    app:tick()
    -- slot2 may now hold its OWN fresh state, but never slot1's pet
    local slot2 = Serialize.decode(mock.store["slot2|" .. Storage.KEY])
    T.eq(#slot2.pets, 0, "slot1's pet must not leak into slot2")
    local slot1 = Serialize.decode(mock.store["slot1|" .. Storage.KEY])
    T.eq(#slot1.pets, 1, "slot1 keeps its pet")
    T.eq(petNames(app), "")
end)

T.test("slots: with subscribe the mod reloads at once, before any other call", function()
    local app, mock = H.new({ slotted = true, subscribe = true, money = 5000 })
    adoptNamed(app, "Alpha")
    mock.switchSlot("slot2")
    T.eq(#app.ctx.state.pets, 0, "state should already be slot2's")
    mock.switchSlot("slot1")
    T.eq(#app.ctx.state.pets, 1)
    T.eq(app.ctx.state.pets[1].name, "Alpha")
end)

T.test("slots: settings and language follow the save", function()
    local app, mock = H.new({ slotted = true })
    app:setSetting("language", "zh-TW")
    T.eq(app:view(1, 101).title, "毛孩之家")
    mock.switchSlot("slot2")
    T.eq(app:view(1, 101).title, "Paw Home", "a fresh save starts with default settings")
    mock.switchSlot("slot1")
    T.eq(app:view(1, 101).title, "毛孩之家")
end)

T.test("slots: an unreadable new slot pauses the mod instead of overwriting it", function()
    local app, mock = H.new({ slotted = true, money = 5000 })
    adoptNamed(app, "Alpha")
    mock.store["slot2|" .. Storage.KEY] = Serialize.encode({ version = 999 })
    local before = mock.store["slot2|" .. Storage.KEY]
    mock.switchSlot("slot2")
    T.eq(app:tick() and #app:tick() or 0, 0)
    local r = app:perform(1, 101, "feed")
    T.falsy(r.ok)
    app:setSetting("lifeScale", 2)
    T.eq(mock.store["slot2|" .. Storage.KEY], before, "the newer save must be left exactly as it was")
    mock.switchSlot("slot1")
    T.eq(petNames(app), "Alpha", "the mod recovers when a readable save is loaded")
end)

T.test("slots: adapters without slots behave exactly as before", function()
    local app, mock = H.new()
    adoptNamed(app, "Solo")
    T.eq(app.slot, nil)
    H.advance(app, mock, 60)
    T.eq(petNames(app), "Solo")
end)

T.test("slots: a second app on the same slotted store sees the saved data", function()
    local mock = Mock.new({ slotted = true, money = 5000 })
    local app = assert(App.new(mock, { seed = 1 }))
    app:tick()
    adoptNamed(app, "Alpha")
    mock.switchSlot("slot2")
    adoptNamed(app, "Beta")
    local again = assert(App.new(mock, { seed = 2 }))   -- "restart" while slot2 is loaded
    T.eq(petNames(again), "Beta")
    mock.switchSlot("slot1")
    T.eq(petNames(again), "Alpha")
end)
